-- Миграция 013: жилые комнаты только со второго этажа
-- Первый этаж занимают помещения администрации (управление, прачечная,
-- пункт оформления), поэтому жилых комнат на нём нет.
-- Ограничение с прежним именем заменяется на более строгое.
-- Если в таблице rooms уже есть комнаты на первом этаже,
-- миграция завершится ошибкой и будет отменена.

ALTER TABLE rooms DROP CONSTRAINT rooms_floor_check;

ALTER TABLE rooms
  ADD CONSTRAINT rooms_floor_check CHECK (floor >= 2);